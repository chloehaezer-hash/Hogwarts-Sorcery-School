/* ================= VARIABLES ================= */

let currentQuestion = 0;


let scores = {

    aurelion: 0,

    corvane: 0,

    fidelis: 0,

    vesperyn: 0

};



/* ================= ELEMENTS ================= */

const startScreen =
    document.getElementById("start-screen");


const beginButton =
    document.getElementById("begin-btn");


const sortingResult =
    document.getElementById("sorting-result");


const music =
    document.getElementById("sorting-music");


const musicControl =
    document.getElementById("music-control");



/* ================= START SORTING ================= */

function startSorting() {

    currentQuestion = 0;


    scores = {

        aurelion: 0,

        corvane: 0,

        fidelis: 0,

        vesperyn: 0

    };


    startScreen.style.display = "none";

    sortingResult.style.display = "block";


    /* Start music after user interaction */

    music.play().catch(function () {

        console.log(
            "Music membutuhkan izin browser."
        );

    });


    showQuestion();

}



/* ================= SHOW QUESTION ================= */

function showQuestion() {

    const question =
        questions[currentQuestion];


    sortingResult.innerHTML = `

        <div class="quiz-box">


            <p class="question-number">

                QUESTION
                ${currentQuestion + 1}
                OF
                ${questions.length}

            </p>


            <h3>

                ${question.question}

            </h3>


            <div class="answer-container">


                ${question.answers.map(function(answer) {

                    return `

                        <button
                            type="button"
                            class="answer-button"
                            onclick="chooseAnswer('${answer[1]}')"
                        >

                            ${answer[0]}

                        </button>

                    `;

                }).join("")}


            </div>


        </div>

    `;

}



/* ================= CHOOSE ANSWER ================= */

function chooseAnswer(house) {

    scores[house]++;


    currentQuestion++;


    if (
        currentQuestion <
        questions.length
    ) {

        showQuestion();

    } else {

        showResult();

    }

}



/* ================= RESULT ================= */

